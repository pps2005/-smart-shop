  function guess(s) {
    const m = s.match(/\d+/); if (!m) return null;
    const g = +m[0], G = mem.game; G.tries++;
    if (g === G.n) { mem.pend = ''; mem.game = null; return out(R(`ถูกต้องค่า! คือเลข ${g} ทายไป ${G.tries} ครั้งเอง เก่งมาก! 🎉`, `正解〜！${g}だよ！${G.tries}回で当てたね、すごい！`), 'happy', 'hop', {}, { fx: 'sparkle' }); }
    if (G.tries >= 6) { mem.pend = ''; mem.game = null; return out(R(`อ๊ะ ครบ 6 ครั้งแล้ว เฉลยคือ ${G.n} ค่ะ เล่นใหม่ไหม?`, `残念、6回終わっちゃった！答えは${G.n}だよ。もう一回やる？`), 'wink', 'tilt'); }
    return g < G.n ? out(R(`มากกว่า ${g} ค่ะ ลองอีกที!`, `${g}より大きいよ！もう一回！`), 'think', 'tilt')
      : out(R(`น้อยกว่า ${g} ค่ะ ใกล้แล้ว!`, `${g}より小さいよ！おしい！`), 'think', 'tilt');
  }
  function math(s) {
    const e = s.replace(/เท่ากับ|เท่าไหร่|เท่าไร|ได้เท่าไหร่|ได้|คือ|=|\?|ค่ะ|คะ|ครับ/g, '').replace(/x|×/gi, '*').replace(/÷/g, '/').replace(/บวก/g, '+').replace(/ลบ/g, '-').replace(/คูณ/g, '*').replace(/หาร/g, '/').replace(/\s+/g, '');
    if (!/^[\d.+\-*/()]+$/.test(e) || !/\d[+\-*/]\d|\d[+\-*/]\(/.test(e)) return null;
    let v; try { v = Function('"use strict";return (' + e + ')')(); } catch (er) { return null; }
    if (!isFinite(v)) return null;
    v = Math.round(v * 10000) / 10000;
    return out(R(`${e} = ${v.toLocaleString('th-TH')} ค่ะ ✏️`, `答えは${v}だよ！`), 'happy', 'nod');
  }
